#!/usr/bin/env python3
"""Build Unicode 1-bit, flash-resident font data from verified original OTFs.
Font data retains source licensing. Converter code: GPL-3.0-or-later.
"""
import argparse, base64, hashlib, io, json, math
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont, features
import PIL
from fontTools.ttLib import TTFont

VERSION = 1
DEFAULT_CHARS = ''.join(chr(cp) for cp in range(32,127)) + 'āēīōūĀĒĪŌŪ→←–—‘’“”…°×·'

def sha(data): return hashlib.sha256(data).hexdigest()

def layout_sizes(layout):
    sizes={'regular':set(),'bold':set()}
    def add(region,weight=None):
        preferred=int(region.get('preferred',region.get('font',0)))
        minimum=int(region.get('minimum',preferred))
        if not 6 <= minimum <= preferred <= 400: raise ValueError('Invalid layout font size range')
        style='regular' if int(weight if weight is not None else region.get('weight',900))<=500 else 'bold'
        sizes[style].update(range(minimum,preferred+1))
    if layout.get('schema_version')=='2.0':
        for b in layout['blocks']:
            if not b.get('visible',True): continue
            if b.get('fontFamily','transit')!='transit': raise ValueError('Provide source fonts for non-TransitSans families before firmware conversion')
            weight=900 if b.get('bold',True) else 400
            add(b,weight)
            if b['type']=='departures':
                fields=b.get('rowFields') or {'route':{'fontScale':1},'direction':{'fontScale':.68},'scheduled':{'fontScale':.68},'eta':{'fontScale':1}}
                for f in fields.values():
                    if not f.get('visible',True): continue
                    font=max(6,math.floor(b['font']*f['fontScale']+.5))
                    add({'font':font,'minimum':min(b['minimum'],font)},weight)
    else:
        regions=layout.get('rendering',{}).get('single',{}).get('regions',layout['single'])
        for r in regions.values(): add(r)
        for key in ('header','clock'): add(layout['multi'][key])
        weights=layout.get('rendering',{}).get('multi',{}).get('text_weights',{})
        for key,r in layout['multi']['rows'].items():
            if isinstance(r,dict): add(r,weights.get(key,500 if key in ('journey','scheduled') else 900))
        # The renderer's no-service message uses these sizes as well.
        for r in ({'preferred':34,'minimum':20},{'preferred':55,'minimum':30},{'preferred':24,'minimum':18}):add(r)
    if not any(sizes.values()): raise ValueError('Layout has no visible font regions')
    return sizes

def rasterize(font,ch):
    left,top,right,bottom=font.getbbox(ch,anchor='ls');w,h=max(0,right-left),max(0,bottom-top)
    advance=round(font.getlength(ch)*64)
    if w and h:
        image=Image.new('L',(w,h));ImageDraw.Draw(image).text((-left,-top),ch,font=font,fill=255,anchor='ls')
        raw=image.tobytes();packed=bytearray((w*h+7)//8)
        for i,value in enumerate(raw):
            if value>=128: packed[i//8]|=0x80>>(i%8)
    else: packed=bytearray()
    return {'codepoint':ord(ch),'width':w,'height':h,'x_offset':left,'y_offset':top,'advance_q6':advance},bytes(packed)

def generate(layout_path,source_path,out_path,text_files=()):
    raw_layout=layout_path.read_bytes();layout=json.loads(raw_layout);spec=json.loads(source_path.read_text());sizes=layout_sizes(layout)
    chars=set(DEFAULT_CHARS)
    def text_values(value):
        if isinstance(value,str):chars.update(value)
        elif isinstance(value,dict):
            for v in value.values():text_values(v)
        elif isinstance(value,list):
            for v in value:text_values(v)
    for b in layout.get('blocks',[]):
        for key in ('label','text'):text_values(b.get(key,''))
    for path in text_files:
        raw=path.read_text();text_values(json.loads(raw) if path.suffix=='.json' else raw)
    chars=sorted(ch for ch in chars if ord(ch)>=32 and ch not in '\x7f\r\n\t')
    out_path.mkdir(parents=True,exist_ok=True)
    fonts={};sources={}
    for style,entry in spec['fonts'].items():
        encoded=(source_path.parent/entry['file']).read_bytes();data=base64.b64decode(encoded,validate=False)
        if sha(data)!=entry['sha256']:raise ValueError('Source font checksum mismatch: '+style)
        cmap=TTFont(io.BytesIO(data)).getBestCmap();missing=[ch for ch in chars if ord(ch) not in cmap]
        if missing:raise ValueError('Missing source glyphs: '+repr(missing))
        fonts[style]=data;sources[style]={'sha256':sha(data),'family':entry['family'],'license':entry['license']}
    faces=[];bitmap_total=0
    # All covered glyph pairs retain kerning, so future stop names need no per-word special handling.
    pairs=[(a,b) for a in chars for b in chars if a!=' ' and b!=' ']
    chunks=['// Generated by build_fonts.py. Font data: see firmware/fonts/COPYRIGHT.txt and COPYING.\n#pragma once\n#include "transit_font_types.h"\n']
    manifest={'format':'otd-unicode-1bit-v1','converter_version':VERSION,'layout_sha256':sha(raw_layout),'sources':sources,'rasterizer':{'pillow':PIL.__version__,'freetype':features.version_module('freetype2'),'threshold':128},'codepoints':[ord(c) for c in chars],'faces':[]}
    for style in ('regular','bold'):
        for size in sorted(sizes[style]):
            font=ImageFont.truetype(io.BytesIO(fonts[style]),size);bitmap=bytearray();glyphs=[]
            for ch in chars:
                g,pixels=rasterize(font,ch);g['offset']=len(bitmap);bitmap.extend(pixels);glyphs.append(g)
            advances={ch:g['advance_q6'] for ch,g in zip(chars,glyphs)};indices={ch:i for i,ch in enumerate(chars)}
            kern=[]
            for a,b in pairs:
                delta=round(font.getlength(a+b)*64)-advances[a]-advances[b]
                if delta:kern.append((indices[a],indices[b],delta))
            symbol=f'transit_{style}_{size}';ascent,descent=font.getmetrics()
            chunks.append(f'static const uint8_t {symbol}_bits[] OTD_FONT_FLASH = {{\n')
            chunks.extend(','.join(f'0x{x:02x}' for x in bitmap[i:i+24])+',\n' for i in range(0,len(bitmap),24));chunks.append('};\n')
            chunks.append(f'static const TransitGlyph {symbol}_glyphs[] OTD_FONT_FLASH = {{\n')
            for g in glyphs:chunks.append('{%d,%d,%d,%d,%d,%d,%d},\n'%(g['codepoint'],g['offset'],g['width'],g['height'],g['x_offset'],g['y_offset'],g['advance_q6']))
            chunks.append('};\n')
            chunks.append(f'static const TransitKerning {symbol}_kern[] OTD_FONT_FLASH = {{\n')
            for a,b,k in kern:chunks.append('{%d,%d,%d},\n'%(a,b,k))
            if not kern:chunks.append('{0,0,0},\n')
            chunks.append('};\n');faces.append((symbol,style,size,len(glyphs),len(kern),ascent,descent))
            bitmap_total+=len(bitmap)
            manifest['faces'].append({'symbol':symbol,'style':style,'pixels':size,'glyphs':len(glyphs),'kerning_pairs':len(kern),'bitmap_bytes':len(bitmap),'bitmap_sha256':sha(bitmap),'ascent':ascent,'descent':descent})
    chunks.append('static const TransitFont transit_fonts[] OTD_FONT_FLASH = {\n')
    for sym,style,size,count,kerning,asc,desc in faces:chunks.append('{%d,%s,%d,%d,%d,%d,%s_bits,%s_glyphs,%s_kern},\n'%(size,'true' if style=='bold' else 'false',count,kerning,asc,desc,sym,sym,sym))
    chunks.append('};\nstatic constexpr size_t transit_font_count=sizeof(transit_fonts)/sizeof(transit_fonts[0]);\n')
    manifest['bitmap_bytes']=bitmap_total;manifest['estimated_flash_bytes']=bitmap_total+sum(f['glyphs']*20+f['kerning_pairs']*6+28 for f in manifest['faces']);
    if manifest['estimated_flash_bytes']>4*1024*1024:raise ValueError('Font package exceeds 4 MiB; reduce the layout size ranges or glyph set')
    header=''.join(chunks);manifest['header_sha256']=sha(header.encode())
    (out_path/'transit_fonts.h').write_text(header);(out_path/'transit_fonts_manifest.json').write_text(json.dumps(manifest,indent=2,ensure_ascii=False)+'\n')
    font=ImageFont.truetype(io.BytesIO(fonts['bold']),32);image=Image.new('1',(800,160),1);draw=ImageDraw.Draw(image);draw.text((12,8),'Whangārei · Tīkīpunga · ā ē ī ō ū',font=font,fill=0);draw.text((12,55),'216E  SCHEDULED 08:45  →  DUE',font=font,fill=0);image.save(out_path/'font-preview.png')
    print(json.dumps({'faces':len(faces),'glyphs_per_face':len(chars),'bitmap_bytes':bitmap_total,'output':str(out_path)}))
    return manifest

if __name__=='__main__':
    root=Path(__file__).resolve().parents[2]
    parser=argparse.ArgumentParser();parser.add_argument('--layout',type=Path,default=root/'firmware/layouts/site-default.json');parser.add_argument('--sources',type=Path,default=root/'firmware/fonts/sources.json');parser.add_argument('--out',type=Path,default=root/'firmware/generated');parser.add_argument('--text-file',type=Path,action='append',default=[])
    args=parser.parse_args();generate(args.layout,args.sources,args.out,args.text_file)
